    def test_atlas_count_dimensions_padding_and_frame_boundaries(self):
        p, output = self.profile, self.output
        textures = RP / "textures/entity/video_screen_big"
        self.assertEqual(output["atlasCount"], math.ceil(output["frameCount"] / p.capacity))
        self.assertEqual(sorted(f.name for f in textures.glob("*.png")),
                         [f"atlas_{i:03d}.png" for i in range(output["atlasCount"])] + ["black.png"])
        hashes = set()
        for index in range(output["atlasCount"]):
            with Image.open(textures / f"atlas_{index:03d}.png") as atlas:
                self.assertEqual(atlas.size, (p.atlas_width, p.atlas_height))
                self.assertLessEqual(max(atlas.size), 2048)
                self.assertEqual(atlas.mode, "RGB")
                used = min(p.capacity, output["frameCount"] - index * p.capacity)
                for slot in range(used):
                    x, y = slot % p.cols * p.cell_width, slot // p.cols * p.cell_height
                    cell = atlas.crop((x, y, x + p.cell_width, y + p.cell_height))
                    pairs = [((0, 1, 1, p.height + 1), (1, 1, 2, p.height + 1)),
                             ((p.width + 1, 1, p.width + 2, p.height + 1), (p.width, 1, p.width + 1, p.height + 1)),
                             ((1, 0, p.width + 1, 1), (1, 1, p.width + 1, 2)),
                             ((1, p.height + 1, p.width + 1, p.height + 2), (1, p.height, p.width + 1, p.height + 1))]
                    for border, adjacent in pairs:
                        self.assertIsNone(ImageChops.difference(cell.crop(border), cell.crop(adjacent)).getbbox(),
                                          f"atlas {index}, slot {slot}, border {border}")
                    for corner, adjacent in [((0, 0), (1, 1)), ((p.width + 1, 0), (p.width, 1)),
                                             ((0, p.height + 1), (1, p.height)),
                                             ((p.width + 1, p.height + 1), (p.width, p.height))]:
                        self.assertEqual(cell.getpixel(corner), cell.getpixel(adjacent))
                    if slot in {0, used // 2, used - 1}:
                        hashes.add(hashlib.sha256(cell.tobytes()).hexdigest())
                for slot in range(used, p.capacity):
                    x, y = slot % p.cols * p.cell_width, slot // p.cols * p.cell_height
                    self.assertIsNone(atlas.crop((x, y, x + p.cell_width, y + p.cell_height)).getbbox())
        self.assertGreater(len(hashes), 20)
        with Image.open(textures / "black.png") as black:
            self.assertEqual(black.size, (1, 1))
            self.assertEqual(black.getpixel((0, 0)), (0, 0, 0))

