    def test_big_definitions_are_reproducible_and_manifest_is_not_owned(self):
        media = {key: self.output[key] for key in ("fps", "frameCount", "duration", "sound")}
        with tempfile.TemporaryDirectory(prefix="big-video-definitions-") as temporary:
            root = Path(temporary)
            write_definitions(root, media, self.output["atlasCount"], self.profile)
            for path in root.rglob("*"):
                if path.is_file():
                    self.assertEqual(path.read_bytes(), (ROOT / path.relative_to(root)).read_bytes(), str(path))
            self.assertFalse(list(root.rglob("manifest.json")))
            self.assertFalse((root / "minecraft/resource_packs/ichiyon_avatar_rp").exists())

