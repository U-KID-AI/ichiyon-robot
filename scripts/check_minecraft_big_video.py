    def test_report_sizes_and_memory(self):
        p, out = self.profile, self.output
        textures = RP / "textures/entity/video_screen_big"
        png_bytes = sum(f.stat().st_size for f in textures.glob("atlas_*.png"))
        audio_bytes = (RP / "sounds/video_screen_big/audio.ogg").stat().st_size
        self.assertEqual(out["atlasPngBytes"], png_bytes)
        self.assertEqual(out["audioBytes"], audio_bytes)
        self.assertEqual(out["assetBytes"], png_bytes + audio_bytes + (textures / "black.png").stat().st_size)
        self.assertLess(out["assetBytes"], 100 * 1024 * 1024)
        rgba = out["atlasCount"] * p.atlas_width * p.atlas_height * 4
        self.assertEqual(out["decodedRgbaBytes"], rgba)
        self.assertEqual(out["decodedRgbaWithMipmapsBytes"], math.ceil(rgba * 4 / 3))
        self.assertEqual(out["decodedRgbaPerAtlasBytes"], p.atlas_width * p.atlas_height * 4)
        # Git normalizes JSON/material newlines; the report records build-host bytes.
        lf_bytes, crlf_bytes = 0, 0
        for path in RP.rglob("*"):
            if not path.is_file() or path.name == "manifest.json":
                continue
            data = path.read_bytes()
            if path.suffix in {".json", ".material"}:
                data = data.replace(b"\r\n", b"\n")
                crlf_bytes += len(data.replace(b"\n", b"\r\n"))
            else:
                crlf_bytes += len(data)
            lf_bytes += len(data)
        self.assertIn(out["generatedPackBytesExcludingManifest"], {lf_bytes, crlf_bytes})

