def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


class BigVideoChecks(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.report = read(REPORT_DIR / "build_report.json")
        cls.output = cls.report["output"]
        cls.profile = BIG_PROFILES[cls.output["profile"]]

    def test_source_and_20fps_contract(self):
        source, output = self.report["source"], self.output
        self.assertEqual((source["width"], source["height"], source["fps"], source["frameCount"]),
                         (640, 360, "24/1", 12244))
        self.assertEqual(source["bytes"], 24332100)
        self.assertEqual(source["audio"], {"codec": "aac", "channels": 2, "sampleRate": 44100})
        self.assertEqual((output["frameWidth"], output["frameHeight"], output["fps"]), (128, 72, 20))
        self.assertEqual(output["duration"], output["frameCount"] / 20)
        self.assertLess(abs(output["duration"] - source["videoDuration"]), 1 / 20)
        self.assertEqual(output["sound"], "ichiyon.video_screen_big.audio")

    def test_generated_javascript(self):
        script = (SCRIPTS / "video_big_media.generated.js").read_text(encoding="utf-8")
        prefix = "// Generated by scripts/build_minecraft_video.py. Do not edit.\nexport const VIDEO_BIG_MEDIA = "
        self.assertTrue(script.startswith(prefix))
        self.assertTrue(script.endswith(";\n"))
        media = json.loads(script[len(prefix):-2])
        self.assertEqual(media, {key: self.output[key] for key in ("fps", "frameCount", "duration", "sound")})
        subprocess.run(["node", "--input-type=module", "--check"], input=script.encode(), check=True,
                       capture_output=True)

    def test_only_synchronized_frame_property(self):
        entity = read(BP / "entities/video_screen_big.json")["minecraft:entity"]
        self.assertEqual(entity["description"]["identifier"], "ichiyon:video_screen_big")
        self.assertEqual(entity["description"]["properties"], {"ichiyon:frame": {
            "type": "int", "range": [-1, self.output["frameCount"] - 1], "default": -1, "client_sync": True}})
        components = entity["components"]
        self.assertEqual(components["minecraft:type_family"]["family"], ["ichiyon_video_screen_big"])
        self.assertEqual(components["minecraft:collision_box"], {"width": 0, "height": 0})
        self.assertEqual(components["minecraft:physics"], {"has_gravity": False, "has_collision": False})
        self.assertIn("minecraft:persistent", components)

    def test_geometry_facing_planes_and_bounds(self):
        geometries = read(RP / "models/entity/video_screen_big.geo.json")["minecraft:geometry"]
        self.assertEqual(len(geometries), 2)
        video, black = [g["bones"][0]["cubes"][0] for g in geometries]
        self.assertEqual(video["size"], [176 * 16 / 9, 176, 0])
        self.assertEqual(black["size"], [384, 176, 0])
        for cube, z in [(video, -0.5), (black, 0)]:
            self.assertEqual(cube["origin"], [-cube["size"][0] / 2, 0, z])
            self.assertEqual(set(cube["uv"]), {"north"})
        self.assertGreater(-video["origin"][2], -black["origin"][2])
        self.assertAlmostEqual((black["size"][0] - video["size"][0]) / 32, 2.2222222222222223)
        for geometry in geometries:
            desc = geometry["description"]
            self.assertEqual((desc["visible_bounds_width"], desc["visible_bounds_height"]), (26, 13))
            self.assertEqual(desc["visible_bounds_offset"], [0, 5.5, 0])

